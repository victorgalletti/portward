"""Converts the Natural Earth 1:50m TopoJSON (public domain) into SVG paths in
an equirectangular projection (x = (lon+180)*k, y = (90-lat)*k, k = 1000/360).
Usage: python3 make_world.py world-50m.json out.js"""
import json, sys

topo = json.load(open(sys.argv[1]))
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]
K = 1000 / 360

arcs = []
for arc in topo["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        lon, lat = x * sx + tx, y * sy + ty
        pts.append(((lon + 180) * K, (90 - lat) * K))
    arcs.append(pts)

def ring(idx):
    out = []
    for i in idx:
        pts = arcs[i] if i >= 0 else arcs[~i][::-1]
        out.extend(pts if not out else pts[1:])
    return out

def path_of(geom):
    polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
    d = []
    for poly in polys:
        for r in poly:
            pts = ring(r)
            # drop points closer than 0.15 units to keep the file small
            simp = [pts[0]]
            for p in pts[1:]:
                if abs(p[0] - simp[-1][0]) + abs(p[1] - simp[-1][1]) > 0.15:
                    simp.append(p)
            if len(simp) < 3:
                continue
            d.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in simp) + "Z")
    return "".join(d)

objs = topo["objects"]
land = "".join(path_of(g) for g in (objs["land"]["geometries"] if "geometries" in objs["land"] else [objs["land"]]))
countries = ""
if "countries" in objs:
    countries = "".join(path_of(g) for g in objs["countries"]["geometries"] if g.get("arcs"))
with open(sys.argv[2], "w") as f:
    f.write("// Generated by scripts/make_world.py from Natural Earth 1:50m (public domain).\n")
    f.write(f"const WORLD_LAND = {json.dumps(land)};\nconst WORLD_COUNTRIES = {json.dumps(countries)};\n")
print(len(land), len(countries))
